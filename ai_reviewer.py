import json
import os
import time
from google import genai
from google.genai import types
from google.colab import userdata

# 1. Securely fetch the API key from Colab Secrets
try:
    api_key = userdata.get('GEMINI_API_KEY')
    client = genai.Client(api_key=api_key)
except userdata.SecretNotFoundError:
    print("❌ Error: Please set 'GEMINI_API_KEY' in the Colab Secrets tab (🔑 icon on the left).")
    client = None

LOG_FILE = "flagged_transactions.jsonl"
OUTPUT_DIR = "investigation_reports"
TRACKER_FILE = "processed_lines.txt"

os.makedirs(OUTPUT_DIR, exist_ok=True)

def generate_analyst_report(tx_data):
    prompt = f"""
    You are a Senior Fraud Investigator at a major financial institution.
    Review the following flagged transaction data, which was blocked by our neuro-symbolic pipeline (1D CNN + XGBoost).

    Transaction Data:
    {json.dumps(tx_data, indent=2)}

    Write a formal, concise "Incident Review Report" (around 150-200 words).
    Format it with these three sections:
    1. Executive Summary
    2. Primary Risk Drivers (Explain the mathematical features in plain English)
    3. Recommended Action (e.g., Freeze account, contact customer, monitor)

    Keep the tone highly professional and analytical. Do not invent any data; rely only on the provided features.
    """

    try:
        response = client.models.generate_content(
            model='gemini-2.5-flash',
            contents=prompt,
            config=types.GenerateContentConfig(temperature=0.2)
        )
        return response.text
    except Exception as e:
        return f"Error generating report: {e}"

def process_audit_logs():
    if not client: return

    print(f"Starting Colab Offline Dashboard. Scanning for {LOG_FILE}...")

    if not os.path.exists(LOG_FILE):
        print(f"❌ No flagged transactions found. Please upload '{LOG_FILE}' to the file explorer on the left.")
        return

    if os.path.exists(TRACKER_FILE):
        with open(TRACKER_FILE, "r") as f:
            processed_lines = set(f.read().splitlines())
    else:
        processed_lines = set()

    with open(LOG_FILE, "r") as log, open(TRACKER_FILE, "a") as tracker:
        for line_num, line in enumerate(log):
            line_id = str(line_num)

            if line_id in processed_lines:
                continue

            tx_data = json.loads(line.strip())
            timestamp = tx_data.get('timestamp', 'unknown_time')
            product = tx_data.get('product_class', 'UNKNOWN')

            print(f"Processing flagged transaction from {timestamp}...")

            report_text = generate_analyst_report(tx_data)

            timestamp_clean = timestamp.replace(":", "").replace("-", "").replace(".", "_")
            report_filename = f"Incident_Report_{product}_{timestamp_clean}.md"
            report_path = os.path.join(OUTPUT_DIR, report_filename)

            with open(report_path, "w", encoding="utf-8") as out_file:
                out_file.write(report_text)

            print(f"✅ Saved: {report_path}")

            tracker.write(line_id + "\n")
            time.sleep(2)

    print("Dashboard sync complete. Check the 'investigation_reports' folder in the left sidebar to download your files.")

process_audit_logs()